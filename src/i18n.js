// 优先使用已保存的选择，首次访问按浏览器的语言偏好选择。
export function resolveLocale(saved, languages = []) {
  if (Object.hasOwn(messages, saved)) return saved;
  for (const language of languages) {
    const tag = language.toLowerCase().replaceAll('_', '-');
    if (/^zh(?:-|$)/.test(tag)) {
      if (/-hans(?:-|$)/.test(tag)) return 'zh-CN';
      return /(?:^|-)(?:hant|tw|hk|mo)(?:-|$)/.test(tag) ? 'zh-TW' : 'zh-CN';
    }
    if (/^en(?:-|$)/.test(tag)) return 'en';
    if (/^ja(?:-|$)/.test(tag)) return 'ja';
  }
  return 'zh-CN';
}

export function translate(locale, key, values = {}) {
  return messages[locale][key].replace(/\{(\w+)\}/g, (match, name) => values[name] ?? match);
}

